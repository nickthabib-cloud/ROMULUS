def hypotheses_for(objective: str) -> list[Hypothesis]:
    """Return diverse deterministic seeds when model planning is unavailable."""
    text = objective.lower()
    selected: list[str] = []
    groups = (
        (("lateral", "remote service", "remote execution", "psexec"), ("T1021.001", "T1021.002", "T1021.003", "T1021.004", "T1021.006", "T1047", "T1210", "T1078", "T1569.002")),
        (("credential", "brute", "password", "logon", "authentication"), ("T1110", "T1003", "T1552.001", "T1078")),
        (("powershell", "script", "execution", "shell"), ("T1059.001", "T1059.003", "T1059.004", "T1047")),
        (("command and control", "c2", "beacon", "outbound", "tunnel"), ("T1071.001", "T1071.004", "T1095", "T1572", "T1219")),
        (("download", "payload", "transfer", "wget", "curl", "linpeas", "meterpreter"), ("T1105", "T1016.001", "T1059.004")),
        (("persist", "service", "scheduled task"), ("T1543.003", "T1569.002", "T1053.005", "T1078")),
        (("scan", "discovery", "enumerat", "reconnaissance"), ("T1087", "T1082", "T1018", "T1046", "T1016.001")),
        (("exfil", "collection", "archive", "staging"), ("T1074", "T1041", "T1567")),
        (("ransom", "impact", "destructive", "recovery"), ("T1486", "T1490", "T1562.001")),
    )
    for needles, tids in groups:
        if any(needle in text for needle in needles): selected.extend(tids)
    for alias, tids in {"rdp":("T1021.001",), "smb":("T1021.002",), "dcom":("T1021.003",),
                        "ssh":("T1021.004",), "winrm":("T1021.006",), "dns":("T1071.004",)}.items():
        if alias in text: selected.extend(tids)
    broad = not selected or any(x in text for x in ("broad hunt", "broad threat hunt", "malicious actors", "all available"))
    if broad: selected = list(BROAD_PORTFOLIO)
    selected = list(dict.fromkeys(x for x in selected if x in TECHNIQUES))[:24]
    result = []
    for index, tid in enumerate(selected):
        item = TECHNIQUES[tid]
        result.append(Hypothesis(
            hypothesis_id="H-" + tid.replace(".", "-"), title=f"Possible {item['name']} activity", technique_id=tid,
            rationale=f"Test the invariant behavior and causal chain relevant to {item['tactic']}; a match is a lead, not proof.",
            expected_host=item["host"], expected_network=item["network"], benign_explanations=item["benign"],
            tactics=item["tactics"], detection_strategies=item["detection_strategies"], data_components=item["data_components"],
            analytic_goal=item["analytic_goal"], mutable_elements=item["mutable_elements"],
            priority=5 if index < 6 else (4 if index < 14 else 3),
        ))
    return result
