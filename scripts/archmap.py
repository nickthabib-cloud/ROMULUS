"""Generate docs/architecture/MODULE_MAP.md from the source tree and enforce layer rules.

Usage:
    python scripts/archmap.py           # rewrite MODULE_MAP.md
    python scripts/archmap.py --check   # exit 1 if MODULE_MAP.md is stale or a layer rule is broken
"""
from __future__ import annotations

import ast
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src" / "romulus"
OUT = ROOT / "docs" / "architecture" / "MODULE_MAP.md"

# package -> packages it must never import (see ARCHITECTURE.md "Dependency rules")
LAYER_RULES: dict[str, set[str]] = {
    "*": {"web", "cli"},
    "detect": {"sources"},
    "decide": {"sources"},
    "correlate": {"sources"},
    "report": {"sources"},
    "agent": {"sources"},
    "store": {"mission", "sources", "evidence", "detect", "decide", "agent", "correlate", "report", "worker"},
}


def module_name(path: Path) -> str:
    rel = path.relative_to(SRC.parent).with_suffix("")
    parts = list(rel.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def scan() -> tuple[dict[str, str], dict[str, set[str]]]:
    docs: dict[str, str] = {}
    imports: dict[str, set[str]] = defaultdict(set)
    if not SRC.exists():
        return docs, imports
    for path in sorted(SRC.rglob("*.py")):
        mod = module_name(path)
        tree = ast.parse(path.read_text(encoding="utf-8-sig"), filename=str(path))
        doc = ast.get_docstring(tree) or ""
        docs[mod] = doc.strip().splitlines()[0] if doc.strip() else ""
        pkg_parts = mod.split(".") if path.name == "__init__.py" else mod.split(".")[:-1]
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    if a.name.startswith("romulus"):
                        imports[mod].add(a.name)
            elif isinstance(node, ast.ImportFrom):
                if node.level:
                    base = pkg_parts[: len(pkg_parts) - node.level + 1]
                    target = ".".join(base + ([node.module] if node.module else []))
                else:
                    target = node.module or ""
                if target.startswith("romulus"):
                    imports[mod].add(target)
    return docs, imports


def top(mod: str) -> str:
    parts = mod.split(".")
    return parts[1] if len(parts) > 1 else ""


def violations(imports: dict[str, set[str]]) -> list[str]:
    out = []
    for mod, targets in imports.items():
        src_pkg = top(mod)
        for t in targets:
            dst_pkg = top(t)
            if not dst_pkg or dst_pkg == src_pkg:
                continue
            banned = LAYER_RULES.get("*", set()) | LAYER_RULES.get(src_pkg, set())
            if src_pkg in {"web", "cli"}:
                banned = LAYER_RULES.get(src_pkg, set())
            if dst_pkg in banned:
                out.append(f"{mod} imports {t} (layer rule: {src_pkg} must not import {dst_pkg})")
    return sorted(out)


def render(docs: dict[str, str], imports: dict[str, set[str]]) -> str:
    lines = [
        "# Module map (generated)",
        "",
        "Generated by `python scripts/archmap.py`. Do not edit by hand.",
        "",
    ]
    if not docs:
        lines += ["_No modules under `src/romulus/` yet._", ""]
        return "\n".join(lines)
    lines += ["## Modules", "", "| Module | Purpose (first docstring line) | Imports (internal) |", "|---|---|---|"]
    for mod in sorted(docs):
        deps = ", ".join(f"`{d}`" for d in sorted(imports.get(mod, ())))
        lines.append(f"| `{mod}` | {docs[mod] or '_missing docstring_'} | {deps} |")
    pkg_edges: dict[str, set[str]] = defaultdict(set)
    for mod, targets in imports.items():
        for t in targets:
            a, b = top(mod), top(t)
            if a and b and a != b:
                pkg_edges[a].add(b)
    lines += ["", "## Package dependencies", "", "```mermaid", "graph LR"]
    for a in sorted(pkg_edges):
        for b in sorted(pkg_edges[a]):
            lines.append(f"  {a} --> {b}")
    lines += ["```", ""]
    return "\n".join(lines)


def main() -> int:
    docs, imports = scan()
    text = render(docs, imports)
    bad = violations(imports)
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        stale = current != text
        if stale:
            print("MODULE_MAP.md is stale: run `python scripts/archmap.py`")
        for v in bad:
            print("LAYER VIOLATION:", v)
        return 1 if (stale or bad) else 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    for v in bad:
        print("LAYER VIOLATION:", v)
    print(f"wrote {OUT.relative_to(ROOT)} ({len(docs)} modules)")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
